function Replace-AllText {
  param(
    [Parameter(Mandatory = $true)][object]$Doc,
    [Parameter(Mandatory = $true)][string]$OldText,
    [Parameter(Mandatory = $true)][AllowEmptyString()][string]$NewText
  )

  $range = $Doc.Content
  $find = $range.Find
  $find.ClearFormatting()
  $find.Replacement.ClearFormatting()
  $find.Text = $OldText
  $find.Replacement.Text = $NewText
  $find.Forward = $true
  $find.Wrap = 1
  $find.MatchCase = $false
  $find.MatchWholeWord = $false
  $find.MatchWildcards = $false
  [void]$find.Execute($OldText, $false, $false, $false, $false, $false, $true, 1, $false, $NewText, 2)
}

